/// 四语本地化（简体中文 / 繁体中文 / English / 日本語）。
/// 以简体中文为键：zh-Hans 直接返回原文；zh-Hant / en 查表翻译，缺失时回退简体中文。
enum L10n {
    static func t(_ text: String) -> String {
        translate(text, language: SettingsService.shared.settings.displayLanguage)
    }

    /// 纯翻译（不依赖全局设置；zh-Hans 直接返回原文）。
    static func translate(_ text: String, language: String) -> String {
        guard language != "zh-Hans" else { return text }
        return tables[language]?[text] ?? text
    }

    /// 某语言的翻译键集合（用于测试表完整性）。
    static func translationKeys(for language: String) -> Set<String> {
        tables[language].map { Set($0.keys) } ?? []
    }

    /// 带格式化参数的本地化：先翻译格式串，再填入参数（%d / %@ / %%）。
    static func f(_ format: String, _ args: CVarArg...) -> String {
        let translated = t(format)
        return String(format: translated, arguments: args)
    }

    /// 反向查键：若 text 是某条翻译（en/zh-Hant）的值，返回对应的简体中文键，用于语言切换时重译；否则原样返回。
    static func canonicalize(_ text: String) -> String {
        if text.isEmpty { return text }
        return reverseTables[text] ?? text
    }

    private static let reverseTables: [String: String] = {
        var map: [String: String] = [:]
        for (_, table) in tables {
            for (key, value) in table {
                map[value] = key
            }
        }
        return map
    }()

    /// 语言代码 → 界面显示名（按当前语言显示）。
    static func langDisplayName(_ code: String, currentLang: String) -> String {
        switch code {
        case "zh-Hans":
            return currentLang == "en" ? "简体中文 (Simplified Chinese)" : "简体中文"
        case "zh-Hant":
            return currentLang == "en" ? "繁體中文 (Traditional Chinese)" : "繁體中文"
        case "ja":
            return currentLang == "en" ? "日本語 (Japanese)" : "日本語"
        default:
            return currentLang == "en" ? "English" : "英语"
        }
    }

    private static let tables: [String: [String: String]] = [
        "zh-Hant": zhHantTable,
        "en": englishTable,
        "ja": japaneseTable,
    ]

